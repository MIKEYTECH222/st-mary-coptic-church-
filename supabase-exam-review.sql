-- =====================================================
-- EXAM REVIEW AND STUDENT PRESENCE SYSTEM
-- =====================================================

-- 1. حالة الطالب أثناء الامتحان

create table if not exists public.quiz_presence_state (
  quiz_id uuid not null
    references public.quizzes(id) on delete cascade,

  member_id uuid not null
    references auth.users(id) on delete cascade,

  status text not null default 'active'
    check (status in ('active', 'away', 'finished')),

  started_at timestamptz not null default now(),

  last_seen_at timestamptz not null default now(),

  left_at timestamptz,

  total_away_seconds bigint not null default 0,

  leave_count integer not null default 0,

  updated_at timestamptz not null default now(),

  primary key (quiz_id, member_id)
);


-- 2. سجل كل أحداث الخروج والعودة

create table if not exists public.quiz_presence_events (
  id bigint generated by default as identity primary key,

  quiz_id uuid not null
    references public.quizzes(id) on delete cascade,

  member_id uuid not null
    references auth.users(id) on delete cascade,

  event_type text not null
    check (
      event_type in (
        'start',
        'leave',
        'return',
        'heartbeat',
        'finish'
      )
    ),

  occurred_at timestamptz not null default now(),

  duration_seconds integer
);


create index if not exists quiz_presence_events_attempt_idx
on public.quiz_presence_events (
  quiz_id,
  member_id,
  occurred_at desc
);


-- 3. تعديلات الخادم على تصحيح الإجابات

create table if not exists public.quiz_answer_reviews (
  attempt_id uuid not null
    references public.quiz_attempts(id) on delete cascade,

  question_id uuid not null
    references public.quiz_questions(id) on delete cascade,

  is_correct boolean not null,

  reviewer_id uuid not null
    references auth.users(id),

  reason text not null,

  reviewed_at timestamptz not null default now(),

  primary key (attempt_id, question_id)
);


-- 4. سجل عمليات إعادة التصحيح

create table if not exists public.quiz_review_logs (
  id bigint generated by default as identity primary key,

  attempt_id uuid not null
    references public.quiz_attempts(id) on delete cascade,

  question_id uuid not null
    references public.quiz_questions(id) on delete cascade,

  reviewer_id uuid not null
    references auth.users(id),

  reason text not null,

  old_is_correct boolean,

  new_is_correct boolean,

  old_score integer not null,

  new_score integer not null,

  old_points integer not null,

  new_points integer not null,

  created_at timestamptz not null default now()
);


-- 5. تفعيل RLS ومنع الوصول المباشر للجداول

alter table public.quiz_presence_state
enable row level security;

alter table public.quiz_presence_events
enable row level security;

alter table public.quiz_answer_reviews
enable row level security;

alter table public.quiz_review_logs
enable row level security;


revoke all on public.quiz_presence_state,
  public.quiz_presence_events,
  public.quiz_answer_reviews,
  public.quiz_review_logs
from anon, authenticated;


-- =====================================================
-- 6. الامتحانات التي يمكن للخادم مراجعتها
-- =====================================================

create or replace function public.get_reviewable_quizzes()

returns table (
  id uuid,
  title text,
  group_id uuid,
  created_at timestamptz,
  points_reward integer,
  is_published boolean
)

language plpgsql
security definer
set search_path = ''

as $$

declare
  v_uid uuid := auth.uid();
  v_role text := public.current_role();

begin

  if
    v_uid is null
    or not public.is_approved_member()
    or not (
      public.is_admin()
      or v_role = 'servant'
    )
  then
    raise exception 'غير مصرح لك بمراجعة الامتحانات';
  end if;


  return query

  select
    q.id,
    q.title,
    q.group_id,
    q.created_at,
    coalesce(q.points_reward, 0),
    q.is_published

  from public.quizzes q

  where
    public.is_admin()

    or (
      v_role = 'servant'

      and q.group_id is not null

      and exists (
        select 1
        from public.servant_group_assignments s

        where
          s.servant_id = v_uid
          and s.group_id = q.group_id
      )
    )

  order by q.created_at desc;

end;

$$;


-- =====================================================
-- 7. تحميل الإجابات ومفاتيح الإجابة للخادم المصرح له
-- =====================================================

create or replace function public.get_quiz_review_data(
  p_quiz_id uuid
)

returns jsonb

language plpgsql
security definer
set search_path = ''

as $$

declare
  v_uid uuid := auth.uid();
  v_role text := public.current_role();
  v_quiz public.quizzes%rowtype;
  v_result jsonb;

begin

  if
    v_uid is null
    or not public.is_approved_member()
    or not (
      public.is_admin()
      or v_role = 'servant'
    )
  then
    raise exception 'غير مصرح لك';
  end if;


  select *
  into v_quiz

  from public.quizzes q

  where q.id = p_quiz_id;


  if not found then
    raise exception 'الامتحان غير موجود';
  end if;


  -- الخادم لا يرى إلا امتحانات مجموعاته

  if not public.is_admin() and (
    v_role <> 'servant'

    or v_quiz.group_id is null

    or not exists (
      select 1
      from public.servant_group_assignments s

      where
        s.servant_id = v_uid
        and s.group_id = v_quiz.group_id
    )
  ) then
    raise exception 'هذا الامتحان ليس ضمن مجموعاتك';
  end if;


  select jsonb_build_object(

    'quiz',

    jsonb_build_object(
      'id', v_quiz.id,
      'title', v_quiz.title,
      'group_id', v_quiz.group_id,
      'points_reward', coalesce(v_quiz.points_reward, 0)
    ),


    'questions',

    coalesce(
      (
        select jsonb_agg(
          jsonb_build_object(
            'id', q.id,
            'question_text', q.question_text,
            'options', q.options,
            'position', q.position,
            'correct_option', k.correct_option
          )
          order by q.position
        )

        from public.quiz_questions q

        join public.quiz_answer_keys k
          on k.question_id = q.id

        where q.quiz_id = v_quiz.id
      ),

      '[]'::jsonb
    ),


    'attempts',

    coalesce(
      (
        select jsonb_agg(
          jsonb_build_object(

            'id', a.id,

            'member_id', a.member_id,

            'member_name',
              coalesce(p.full_name, 'عضو بدون اسم'),

            'score', a.score,

            'max_score', a.max_score,

            'answers', a.answers,

            'submitted_at', a.submitted_at,

            'points_awarded', a.points_awarded,


            'reviews',

            coalesce(
              (
                select jsonb_object_agg(
                  r.question_id::text,
                  r.is_correct
                )

                from public.quiz_answer_reviews r

                where r.attempt_id = a.id
              ),

              '{}'::jsonb
            ),


            'presence',

            (
              select jsonb_build_object(
                'status', s.status,
                'started_at', s.started_at,
                'last_seen_at', s.last_seen_at,
                'left_at', s.left_at,
                'total_away_seconds', s.total_away_seconds,
                'leave_count', s.leave_count
              )

              from public.quiz_presence_state s

              where
                s.quiz_id = a.quiz_id
                and s.member_id = a.member_id
            ),


            'presence_events',

            coalesce(
              (
                select jsonb_agg(
                  jsonb_build_object(
                    'event_type', e.event_type,
                    'occurred_at', e.occurred_at,
                    'duration_seconds', e.duration_seconds
                  )
                  order by e.occurred_at
                )

                from public.quiz_presence_events e

                where
                  e.quiz_id = a.quiz_id
                  and e.member_id = a.member_id
              ),

              '[]'::jsonb
            )

          )

          order by a.submitted_at desc
        )

        from public.quiz_attempts a

        left join public.profiles p
          on p.id = a.member_id

        where a.quiz_id = v_quiz.id
      ),

      '[]'::jsonb
    )

  )

  into v_result;


  return v_result;

end;

$$;


-- =====================================================
-- 8. تحديث حالة الخروج والعودة في صفحة المراجعة
-- =====================================================

create or replace function public.get_quiz_presence_for_quiz(
  p_quiz_id uuid
)

returns jsonb

language plpgsql
security definer
set search_path = ''

as $$

declare
  v_uid uuid := auth.uid();
  v_role text := public.current_role();
  v_group uuid;

begin

  select q.group_id
  into v_group

  from public.quizzes q

  where q.id = p_quiz_id;


  if not found then
    raise exception 'الامتحان غير موجود';
  end if;


  if
    v_uid is null
    or not public.is_approved_member()
    or not (
      public.is_admin()

      or (
        v_role = 'servant'

        and v_group is not null

        and exists (
          select 1
          from public.servant_group_assignments s

          where
            s.servant_id = v_uid
            and s.group_id = v_group
        )
      )
    )
  then
    raise exception 'غير مصرح لك';
  end if;


  return coalesce(
    (
      select jsonb_agg(
        jsonb_build_object(

          'attempt_id', a.id,

          'member_id', a.member_id,

          'status', s.status,

          'left_at', s.left_at,

          'last_seen_at', s.last_seen_at,

          'total_away_seconds', s.total_away_seconds,

          'leave_count', s.leave_count,

          'last_return_seconds',

          (
            select e.duration_seconds

            from public.quiz_presence_events e

            where
              e.quiz_id = a.quiz_id
              and e.member_id = a.member_id
              and e.event_type = 'return'

            order by e.occurred_at desc

            limit 1
          )

        )
      )

      from public.quiz_attempts a

      left join public.quiz_presence_state s
        on
          s.quiz_id = a.quiz_id
          and s.member_id = a.member_id

      where a.quiz_id = p_quiz_id
    ),

    '[]'::jsonb
  );

end;

$$;


-- =====================================================
-- 9. الطالب يرسل بدء / خروج / عودة / اتصال / انتهاء
-- =====================================================

create or replace function public.quiz_presence_ping(
  p_quiz_id uuid,
  p_event text
)

returns void

language plpgsql
security definer
set search_path = ''

as $$

declare
  v_uid uuid := auth.uid();
  v_group uuid;
  v_member_group uuid;
  v_approval text;
  v_status text;
  v_left timestamptz;
  v_duration integer := null;
  v_log_event text := null;

begin

  if v_uid is null then
    raise exception 'يجب تسجيل الدخول';
  end if;


  if p_event not in (
    'start',
    'heartbeat',
    'leave',
    'return',
    'finish'
  ) then
    raise exception 'حدث غير صالح';
  end if;


  select q.group_id
  into v_group

  from public.quizzes q

  where
    q.id = p_quiz_id
    and q.is_published = true;


  if not found then
    raise exception 'الامتحان غير منشور أو غير موجود';
  end if;


  select
    p.group_id,
    p.approval_status

  into
    v_member_group,
    v_approval

  from public.profiles p

  where p.id = v_uid;


  if v_approval is distinct from 'approved' then
    raise exception 'الحساب غير معتمد';
  end if;


  if
    v_group is not null
    and v_group is distinct from v_member_group
  then
    raise exception 'هذا الامتحان ليس ضمن مجموعتك';
  end if;


  if exists (
    select 1
    from public.quiz_attempts a

    where
      a.quiz_id = p_quiz_id
      and a.member_id = v_uid
  ) and p_event <> 'finish' then

    raise exception 'تم تسليم هذا الامتحان بالفعل';

  end if;


  insert into public.quiz_presence_state (
    quiz_id,
    member_id,
    status,
    started_at,
    last_seen_at
  )

  values (
    p_quiz_id,
    v_uid,
    'active',
    now(),
    now()
  )

  on conflict (quiz_id, member_id)
  do nothing;


  select
    s.status,
    s.left_at

  into
    v_status,
    v_left

  from public.quiz_presence_state s

  where
    s.quiz_id = p_quiz_id
    and s.member_id = v_uid

  for update;


  -- خروج الطالب

  if p_event = 'leave' and v_status <> 'away' then

    update public.quiz_presence_state

    set
      status = 'away',
      left_at = now(),
      last_seen_at = now(),
      leave_count = leave_count + 1,
      updated_at = now()

    where
      quiz_id = p_quiz_id
      and member_id = v_uid;


    v_log_event := 'leave';


  -- عودة الطالب

  elsif p_event = 'return' and v_status = 'away' then

    v_duration := greatest(
      0,
      floor(
        extract(epoch from (now() - v_left))
      )::integer
    );


    update public.quiz_presence_state

    set
      status = 'active',
      left_at = null,
      last_seen_at = now(),

      total_away_seconds =
        total_away_seconds + v_duration,

      updated_at = now()

    where
      quiz_id = p_quiz_id
      and member_id = v_uid;


    v_log_event := 'return';


  -- بدء الامتحان

  elsif p_event = 'start' then

    update public.quiz_presence_state

    set
      status = 'active',
      last_seen_at = now(),
      updated_at = now()

    where
      quiz_id = p_quiz_id
      and member_id = v_uid;


    v_log_event := 'start';


  -- اتصال دوري

  elsif p_event = 'heartbeat' then

    update public.quiz_presence_state

    set
      last_seen_at = now(),
      updated_at = now()

    where
      quiz_id = p_quiz_id
      and member_id = v_uid
      and status = 'active';


  -- انتهاء الامتحان

  elsif p_event = 'finish' then

    if v_status = 'away' and v_left is not null then

      v_duration := greatest(
        0,
        floor(
          extract(epoch from (now() - v_left))
        )::integer
      );

    end if;


    update public.quiz_presence_state

    set
      status = 'finished',
      left_at = null,
      last_seen_at = now(),

      total_away_seconds =
        total_away_seconds + coalesce(v_duration, 0),

      updated_at = now()

    where
      quiz_id = p_quiz_id
      and member_id = v_uid;


    v_log_event := 'finish';

  end if;


  if v_log_event is not null then

    insert into public.quiz_presence_events (
      quiz_id,
      member_id,
      event_type,
      duration_seconds
    )

    values (
      p_quiz_id,
      v_uid,
      v_log_event,
      v_duration
    );

  end if;

end;

$$;


-- =====================================================
-- 10. إعادة تصحيح إجابة واحدة وتحديث النقاط
-- =====================================================

create or replace function public.review_quiz_answer(
  p_attempt_id uuid,
  p_question_id uuid,
  p_is_correct boolean,
  p_reason text
)

returns jsonb

language plpgsql
security definer
set search_path = ''

as $$

declare
  v_uid uuid := auth.uid();
  v_role text := public.current_role();

  v_attempt public.quiz_attempts%rowtype;
  v_quiz public.quizzes%rowtype;

  v_old_review boolean;

  v_old_score integer;
  v_new_score integer;

  v_old_points integer;
  v_new_points integer;

  v_delta integer;

  v_reason text :=
    nullif(trim(coalesce(p_reason, '')), '');

begin

  if
    v_uid is null
    or not public.is_approved_member()
  then
    raise exception 'يجب تسجيل الدخول بحساب معتمد';
  end if;


  select *
  into v_attempt

  from public.quiz_attempts a

  where a.id = p_attempt_id

  for update;


  if not found then
    raise exception 'محاولة الامتحان غير موجودة';
  end if;


  select *
  into v_quiz

  from public.quizzes q

  where q.id = v_attempt.quiz_id;


  if not found then
    raise exception 'الامتحان غير موجود';
  end if;


  -- صلاحية الأدمن أو الخادم المسند إليه الامتحان

  if not (
    public.is_admin()

    or (
      v_role = 'servant'

      and v_quiz.group_id is not null

      and exists (
        select 1
        from public.servant_group_assignments s

        where
          s.servant_id = v_uid
          and s.group_id = v_quiz.group_id
      )
    )
  ) then

    raise exception 'لا يمكنك مراجعة هذا الامتحان';

  end if;


  if not exists (
    select 1
    from public.quiz_questions q

    where
      q.id = p_question_id
      and q.quiz_id = v_attempt.quiz_id
  ) then

    raise exception 'السؤال لا يتبع هذا الامتحان';

  end if;


  select r.is_correct

  into v_old_review

  from public.quiz_answer_reviews r

  where
    r.attempt_id = p_attempt_id
    and r.question_id = p_question_id;


  -- NULL يلغي التصحيح اليدوي ويعود إلى الإجابة الأصلية

  if p_is_correct is null then

    delete from public.quiz_answer_reviews

    where
      attempt_id = p_attempt_id
      and question_id = p_question_id;

  else

    if v_reason is null then
      raise exception 'اكتب سبب تعديل التصحيح';
    end if;


    insert into public.quiz_answer_reviews (
      attempt_id,
      question_id,
      is_correct,
      reviewer_id,
      reason,
      reviewed_at
    )

    values (
      p_attempt_id,
      p_question_id,
      p_is_correct,
      v_uid,
      v_reason,
      now()
    )

    on conflict (attempt_id, question_id)

    do update set
      is_correct = excluded.is_correct,
      reviewer_id = excluded.reviewer_id,
      reason = excluded.reason,
      reviewed_at = now();

  end if;


  -- إعادة حساب الدرجة بالكامل

  select

    count(*) filter (

      where coalesce(

        r.is_correct,

        (
          nullif(
            v_attempt.answers ->> q.id::text,
            ''
          ) is not null

          and

          (
            v_attempt.answers ->> q.id::text
          )::integer = k.correct_option
        )

      )

    )::integer

  into v_new_score

  from public.quiz_questions q

  join public.quiz_answer_keys k
    on k.question_id = q.id

  left join public.quiz_answer_reviews r

    on
      r.attempt_id = p_attempt_id
      and r.question_id = q.id

  where q.quiz_id = v_attempt.quiz_id;


  v_old_score := coalesce(v_attempt.score, 0);

  v_old_points := coalesce(v_attempt.points_awarded, 0);

  v_new_score := coalesce(v_new_score, 0);


  -- حساب مكافأة الطالب بناءً على الدرجة الجديدة

  if coalesce(v_attempt.max_score, 0) > 0 then

    v_new_points := floor(

      coalesce(v_quiz.points_reward, 0)::numeric

      * v_new_score::numeric

      / v_attempt.max_score::numeric

    )::integer;

  else

    v_new_points := 0;

  end if;


  v_delta := v_new_points - v_old_points;


  -- تحديث محاولة الطالب

  update public.quiz_attempts

  set
    score = v_new_score,
    points_awarded = v_new_points

  where id = p_attempt_id;


  -- تحديث رصيد الطالب بالفرق فقط

  if v_delta <> 0 then

    update public.profiles

    set points = coalesce(points, 0) + v_delta

    where id = v_attempt.member_id;


    insert into public.point_transactions (
      member_id,
      amount,
      reason,
      awarded_by
    )

    values (
      v_attempt.member_id,
      v_delta,

      'تعديل نقاط بعد مراجعة امتحان: ' ||
      coalesce(v_quiz.title, 'امتحان'),

      v_uid
    );

  end if;


  -- حفظ سجل المراجعة

  insert into public.quiz_review_logs (
    attempt_id,
    question_id,
    reviewer_id,
    reason,
    old_is_correct,
    new_is_correct,
    old_score,
    new_score,
    old_points,
    new_points
  )

  values (
    p_attempt_id,
    p_question_id,
    v_uid,

    coalesce(
      v_reason,
      'إلغاء التعديل اليدوي'
    ),

    v_old_review,
    p_is_correct,

    v_old_score,
    v_new_score,

    v_old_points,
    v_new_points
  );


  return jsonb_build_object(
    'score', v_new_score,
    'max_score', v_attempt.max_score,
    'points_awarded', v_new_points,
    'points_delta', v_delta
  );

end;

$$;


